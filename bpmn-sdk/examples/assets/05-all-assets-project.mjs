export function buildAllAssetsProject(outDir) {
  // a Business Process with a JavaScript script node + a businessRuleTask that fires the DRL
  const process = autowire({
    id: 'com.acme.assets.main', name: 'assets-main', packageName: 'com.acme',
    declarations: { signals: [], errors: [] },
    variables: [{ name: 'caseId', type: 'String' }, { name: 'claim', type: 'com.acme.Claim' }, { name: 'tier', type: 'String' }],
    nodes: [
      { id: '_s', type: 'startEvent', subtype: 'none', name: 'Start', position: { x: 60, y: 120, width: 40, height: 40 } },
      // JAVASCRIPT script node (the goal): JS logic only
      { id: '_js', type: 'scriptTask', name: 'Derive tier (JS)', scriptFormat: JS, position: { x: 150, y: 110, width: 130, height: 60 },
        script: 'var c = kcontext.getVariable("claim");\nkcontext.setVariable("tier", (c != null && c.amount > 100000) ? "HIGH" : "LOW");' },
      // businessRuleTask -> the DRL asset (ruleflow-group "classify")
      { id: '_rules', type: 'businessRuleTask', name: 'Classify (DRL)', ruleFlowGroup: 'classify', implementation: '##unspecified', position: { x: 320, y: 110, width: 130, height: 60 } },
      // userTask -> the form asset
      { id: '_review', type: 'userTask', name: 'Review', taskName: 'review', group: 'ClaimsExaminer', position: { x: 490, y: 110, width: 120, height: 60 } },
      { id: '_e', type: 'endEvent', subtype: 'none', name: 'End', position: { x: 660, y: 120, width: 40, height: 40 } },
    ],
    flows: [
      { id: 'f1', sourceRef: '_s', targetRef: '_js' },
      { id: 'f2', sourceRef: '_js', targetRef: '_rules' },
      { id: 'f3', sourceRef: '_rules', targetRef: '_review' },
      { id: 'f4', sourceRef: '_review', targetRef: '_e' },
    ],
  });
  const v = validateModel(process);
  if (!v.ok) throw new Error('invalid: ' + v.errors.join('; '));

  const project = {
    root: outDir,
    descriptor: {
      gav: { groupId: 'com.acme', artifactId: 'all-assets-bpm', version: '1.0.0-SNAPSHOT', name: 'All Assets BPM', kieVersion: '7.73.0.Final' },
      deployment: {
        runtimeStrategy: 'SINGLETON',
        workItemHandlers: [{ name: 'Rest', resolver: 'mvel', identifier: 'new org.jbpm.process.workitem.rest.RESTWorkItemHandler(classLoader)' }],
        environmentEntries: [{ name: 'INTEGRATION_LAYER_URL', resolver: 'mvel', identifier: '"http://localhost:3000"' }],
      },
      // Work Item definition asset -> generates global/WorkDefinitions.wid
      workDefinitions: [{ name: 'Rest', displayName: 'REST', category: 'Communication', icon: 'defaultresticon.png',
        defaultHandler: 'mvel: new org.jbpm.process.workitem.rest.RESTWorkItemHandler(classLoader)',
        parameters: { Url: 'StringDataType', Method: 'StringDataType' }, results: { Result: 'ObjectDataType' } }],
      // every other asset type, carried verbatim
      files: { ...ASSET_FILES },
    },
    processes: [process],
  };
  const written = writeProject(project, outDir);
  return { outDir, written, project };
}

if (isMain(import.meta.url)) {
  const outDir = defaultOutDir(import.meta.url, 'assets');
  const { written } = buildAllAssetsProject(outDir);
  printWritten('all-assets jBPM project', outDir, written);
}
